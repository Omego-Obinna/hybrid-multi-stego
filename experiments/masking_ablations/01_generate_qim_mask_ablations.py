#!/usr/bin/env python3
"""
Generate Ours-QIM mask-only ablations without image embedding or STC.

Operational formal layer:
  eta = psi(o)
  d   = PRF(k_e, eta)
  mu  = QIM_Delta(P_params; d)
  b   = m XOR mu

Concrete binary dithered-QIM readout:
  a_i=(2d_i-1)Delta/4,
  q_i=round((x_i-a_i)/Delta),
  mu_i=q_i mod 2,
where x_i is generated by a keyed XOF in [0,1).
"""
from __future__ import annotations
import argparse,csv,hashlib,hmac,json,math,os
from pathlib import Path
import numpy as np
from PIL import Image
from scipy.special import erfc,gammaincc

EXTS={'.png','.pgm','.bmp','.tif','.tiff','.jpg','.jpeg'}

def csvlist(s,cast=str):return [cast(x.strip()) for x in s.split(',') if x.strip()]
def hseed(key,*parts):return hmac.new(key,b'\x1f'.join(parts),hashlib.sha256).digest()
def xof(seed,n):return hashlib.shake_256(seed).digest(n)
def bitxof(seed,nbits):
    raw=np.frombuffer(xof(seed,(nbits+7)//8),dtype=np.uint8)
    return np.unpackbits(raw,bitorder='big')[:nbits].astype(np.uint8,copy=False)
def uxof(seed,n):
    raw=np.frombuffer(xof(seed,4*n),dtype='>u4')
    return (raw.astype(np.float64)+0.5)/2**32

def covers(root,n):
    fs=sorted(p for p in root.rglob('*') if p.is_file() and p.suffix.lower() in EXTS)
    if not fs:raise SystemExit(f'[ERROR] no cover images under {root}')
    return fs[:n]

def gray(path):
    with Image.open(path) as im:return np.asarray(im.convert('L'),dtype=np.uint8)

def psi(path,mode):
    if mode=='hashid':return hashlib.sha256(path.read_bytes()).digest()
    a=gray(path).astype(np.float64)
    if mode=='global':
        h=np.bincount(a.astype(np.uint8).ravel(),minlength=256).astype(float); p=h/max(h.sum(),1); nz=p[p>0]
        ent=float(-(nz*np.log2(nz)).sum()); gx=np.diff(a,axis=1); gy=np.diff(a,axis=0)
        q=np.rint(np.array([a.mean(),a.std(),ent,np.mean(abs(gx)),np.mean(abs(gy))])*1000).astype('>i8').tobytes()
        return hashlib.sha256(b'global|'+q).digest()
    if mode=='block':
        h,w=a.shape; vals=[]
        for r in range(8):
            for c in range(8):
                b=a[r*h//8:(r+1)*h//8,c*w//8:(c+1)*w//8]; vals.extend([b.mean(),b.std()])
        q=np.rint(np.asarray(vals)*100).astype('>i4').tobytes(); return hashlib.sha256(b'block|'+q).digest()
    raise SystemExit(f'[ERROR] unsupported psi mode {mode}')

def session_key(master,seed,index,payload):return hseed(master,b'session',str(seed).encode(),str(index).encode(),f'{payload:.6f}'.encode())
def message(kind,n,key,sid,text):
    if kind=='zero':return np.zeros(n,dtype=np.uint8)
    if kind=='alternating':return (np.arange(n,dtype=np.uint64)&1).astype(np.uint8)
    if kind=='lowentropy':return np.resize(np.array([0]*31+[1],dtype=np.uint8),n)
    if kind=='text':return np.resize(np.unpackbits(np.frombuffer(text.encode(),dtype=np.uint8),bitorder='big'),n).astype(np.uint8)
    if kind=='random':return bitxof(hseed(key,b'message',sid),n)
    raise SystemExit(f'[ERROR] unsupported message class {kind}')

def qim_mask(key,eta,n,delta,dither_mode,sid):
    x=uxof(hseed(key,b'P_params',str(n).encode()),n)
    if dither_mode=='cover_prf':d=bitxof(hseed(key,b'dither',eta),n)
    elif dither_mode=='key_only':d=bitxof(hseed(key,b'dither',sid),n)
    elif dither_mode=='zero':d=np.zeros(n,dtype=np.uint8)
    else:raise SystemExit(f'[ERROR] unsupported dither {dither_mode}')
    off=(2*d.astype(float)-1)*(delta/4) if dither_mode!='zero' else np.zeros(n)
    q=np.rint((x-off)/delta).astype(np.int64); return np.mod(q,2).astype(np.uint8)

def longest_run(x):
    if len(x)==0:return 0
    z=np.flatnonzero(np.diff(x)!=0)+1; return int(np.diff(np.r_[0,z,len(x)]).max())

def apen(x,m=2,maxbits=65536):
    x=x[:maxbits]; n=len(x)
    if n<=m+1:return float('nan')
    def phi(mm):
        ext=np.r_[x,x[:mm-1]]; counts=np.zeros(2**mm,dtype=np.int64); code=0; mask=2**mm-1
        for i,b in enumerate(ext):
            code=((code<<1)|int(b))&mask
            if i>=mm-1 and i-mm+1<n:counts[code]+=1
        p=counts[counts>0]/n; return float(np.sum(p*np.log(p)))
    return phi(m)-phi(m+1)

def diag(x,block=128):
    n=len(x); p1=float(x.mean()); h=-math.log2(max(p1,1-p1)) if 0<p1<1 else 0.0
    s=2*x.astype(float)-1; mon=float(erfc(abs(s.sum())/math.sqrt(2*n)))
    trans=int(np.count_nonzero(x[1:]!=x[:-1])); pi=p1
    if n>1 and abs(pi-.5)<2/math.sqrt(n):
        runs=trans+1; rp=float(erfc(abs(runs-2*n*pi*(1-pi))/(2*math.sqrt(2*n)*pi*(1-pi))))
    else:rp=0.0
    nb=n//block
    if nb:
        b=x[:nb*block].reshape(nb,block); props=b.mean(1); chi=4*block*np.sum((props-.5)**2); bp=float(gammaincc(nb/2,chi/2)); mb=float(np.mean(abs(props-.5)))
    else:bp=mb=float('nan')
    serial=float(np.corrcoef(x[:-1],x[1:])[0,1]) if n>2 and x.std()>0 else 0.0
    return {'n_bits':n,'ones_ratio':p1,'absolute_bias':abs(p1-.5),'min_entropy_per_bit':h,'serial_correlation_lag1':serial,'transition_rate':trans/max(n-1,1),'longest_run':longest_run(x),'approximate_entropy_m2':apen(x),'monobit_p':mon,'runs_p':rp,'block_frequency_p':bp,'mean_block_bias':mb}

def featrows(x,label,seed,idx,cfg,payload,msg,wbits,maxw):
    out=[]
    for w in range(min(len(x)//wbits,maxw)):
        d=diag(x[w*wbits:(w+1)*wbits],64)
        out.append({'label':label,'seed':seed,'cover_index':idx,'group_id':f'{seed}:{idx}','config_id':cfg,'payload_bpp':payload,'message_class':msg,'window_index':w,**{k:d[k] for k in ['ones_ratio','absolute_bias','min_entropy_per_bit','serial_correlation_lag1','transition_rate','longest_run','approximate_entropy_m2','mean_block_bias']}})
    return out

def configs(psis,scales):
    out=[{'psi_mode':p,'dither_mode':'cover_prf','delta_scale':s} for p in psis for s in scales]
    ref='hashid' if 'hashid' in psis else psis[0]
    out += [{'psi_mode':ref,'dither_mode':'key_only','delta_scale':1.0},{'psi_mode':ref,'dither_mode':'zero','delta_scale':1.0}]
    return out

class Writer:
    def __init__(self,path,maxbits):self.path=path;self.max=maxbits;self.n=0;path.parent.mkdir(parents=True,exist_ok=True);self.f=path.open('wb')
    def add(self,x):
        k=min(len(x),self.max-self.n)
        if k>0:self.f.write(np.packbits(x[:k],bitorder='big').tobytes());self.n+=k
    def close(self):self.f.close()

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--cover-root',required=True); ap.add_argument('--out-dir',required=True); ap.add_argument('--payloads',default='0.10,0.20,0.40'); ap.add_argument('--seeds',default='42,43,44'); ap.add_argument('--covers',type=int,default=50); ap.add_argument('--psi-modes',default='hashid,global,block'); ap.add_argument('--delta-scales',default='0.5,1.0,2.0'); ap.add_argument('--base-delta',type=float,default=.25); ap.add_argument('--message-classes',default='zero,alternating,lowentropy,text,random'); ap.add_argument('--text-message',default='Hybrid multichannel steganography masking ablation. '); ap.add_argument('--window-bits',type=int,default=2048); ap.add_argument('--windows-per-sample',type=int,default=4); ap.add_argument('--nist-max-bits',type=int,default=2000000); ap.add_argument('--nist-message-classes',default='zero,text,random'); ap.add_argument('--key-hex'); a=ap.parse_args()
    keyhex=a.key_hex or os.environ.get('QIM_MASK_ABLATION_KEY')
    if not keyhex:raise SystemExit('[ERROR] set QIM_MASK_ABLATION_KEY to a benchmark-only 64-hex-character key')
    master=bytes.fromhex(keyhex)
    if len(master)<32:raise SystemExit('[ERROR] key must be at least 32 bytes')
    out=Path(a.out_dir).expanduser().resolve(); out.mkdir(parents=True,exist_ok=True); bitdir=out/'bitstreams'; bitdir.mkdir(exist_ok=True)
    ps=csvlist(a.payloads,float); seeds=csvlist(a.seeds,int); pm=csvlist(a.psi_modes); scales=csvlist(a.delta_scales,float); msgs=csvlist(a.message_classes); nist=set(csvlist(a.nist_message_classes)); cfgs=configs(pm,scales); covs=covers(Path(a.cover_root).expanduser().resolve(),a.covers)
    mfields=['config_id','psi_mode','dither_mode','delta_scale','delta','payload_bpp','seed','cover_index','cover_name','message_class','stream','n_bits','ones_ratio','absolute_bias','min_entropy_per_bit','serial_correlation_lag1','transition_rate','longest_run','approximate_entropy_m2','monobit_p','runs_p','block_frequency_p','mean_block_bias']
    ffields=['label','seed','cover_index','group_id','config_id','payload_bpp','message_class','window_index','ones_ratio','absolute_bias','min_entropy_per_bit','serial_correlation_lag1','transition_rate','longest_run','approximate_entropy_m2','mean_block_bias']
    writers={}; manifest=[]
    with (out/'mask_sample_metrics.csv').open('w',newline='',encoding='utf-8') as mf,(out/'mask_classifier_features.csv').open('w',newline='',encoding='utf-8') as ff:
        mw=csv.DictWriter(mf,fieldnames=mfields); fw=csv.DictWriter(ff,fieldnames=ffields); mw.writeheader();fw.writeheader()
        for seed in seeds:
            for payload in ps:
                nbits=int(round(payload*512*512))
                for idx,path in enumerate(covs):
                    sid=f'{seed}:{payload:.2f}:{idx}'.encode(); ke=session_key(master,seed,idx,payload)
                    for ci,cfg in enumerate(cfgs):
                        cid=f'cfg_{ci:02d}'; eta=psi(path,cfg['psi_mode']); delta=a.base_delta*cfg['delta_scale']; mu=qim_mask(ke,eta,nbits,delta,cfg['dither_mode'],sid)
                        mw.writerow({'config_id':cid,**cfg,'delta':delta,'payload_bpp':payload,'seed':seed,'cover_index':idx,'cover_name':path.name,'message_class':'NA','stream':'mu',**diag(mu)})
                        for msg in msgs:
                            b=np.bitwise_xor(message(msg,nbits,ke,sid,a.text_message),mu); mw.writerow({'config_id':cid,**cfg,'delta':delta,'payload_bpp':payload,'seed':seed,'cover_index':idx,'cover_name':path.name,'message_class':msg,'stream':'b',**diag(b)})
                            u=bitxof(hseed(ke,b'uniform',cid.encode(),msg.encode()),nbits)
                            for r in featrows(b,1,seed,idx,cid,payload,msg,a.window_bits,a.windows_per_sample):fw.writerow(r)
                            for r in featrows(u,0,seed,idx,cid,payload,msg,a.window_bits,a.windows_per_sample):fw.writerow(r)
                            if msg in nist:
                                k=(cid,payload,seed,msg)
                                if k not in writers:
                                    p=bitdir/f'{cid}_p{int(round(payload*100)):03d}_seed{seed}_{msg}.bin'; writers[k]=Writer(p,a.nist_max_bits); manifest.append({'config_id':cid,**cfg,'delta':delta,'payload_bpp':payload,'seed':seed,'message_class':msg,'path':str(p),'target_bits':a.nist_max_bits})
                                writers[k].add(b)
                    print(f'[RUN] seed={seed} payload={payload:.2f} cover={idx+1}/{len(covs)}',flush=True)
    for w in writers.values():w.close()
    for r in manifest:r['actual_bits']=writers[(r['config_id'],r['payload_bpp'],r['seed'],r['message_class'])].n
    with (out/'bitstream_manifest.csv').open('w',newline='',encoding='utf-8') as f:
        fields=['config_id','psi_mode','dither_mode','delta_scale','delta','payload_bpp','seed','message_class','path','target_bits','actual_bits'];w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(manifest)
    with (out/'mask_ablation_configs.csv').open('w',newline='',encoding='utf-8') as f:
        fields=['config_id','psi_mode','dither_mode','delta_scale','delta'];w=csv.DictWriter(f,fieldnames=fields);w.writeheader();[w.writerow({'config_id':f'cfg_{i:02d}',**c,'delta':a.base_delta*c['delta_scale']}) for i,c in enumerate(cfgs)]
    meta={'formal_mask_only':True,'image_embedding_performed':False,'covers':len(covs),'payloads':ps,'seeds':seeds,'configs':cfgs,'message_classes':msgs,'base_delta':a.base_delta,'qim_readout':'a_i=(2d_i-1)Delta/4; q_i=round((x_i-a_i)/Delta); mu_i=q_i mod 2','warning':'Operational instantiation of the formal mask layer; replace qim_mask() if the manuscript uses another exact QIM readout.'}
    (out/'mask_generation_metadata.json').write_text(json.dumps(meta,indent=2)+'\n',encoding='utf-8')
    print('[OK] No image embedding or STC execution was performed.')
if __name__=='__main__':main()
